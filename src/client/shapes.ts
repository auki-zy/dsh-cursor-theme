/**
 * dsh-cursor-theme pixel shape library (M4).
 *
 * Creative shapes defined as 16×16 pixel-art matrices (`#` = foreground,
 * `.` = transparent). Rendered at 2× (32×32) for cursors. Each shape also
 * carries the state ids it suits and the CSS fallback keyword.
 *
 * The same table drives:
 *   - the Node asset generator (scripts/generate-assets.mjs → PNG data URLs)
 *   - the browser AI-theme renderer (src/client/render.ts → canvas PNGs)
 *   - the built-in theme catalog (shape + palette combos)
 */

export interface PixelShape {
  id: string
  /** Human name (en). */
  name: string
  /** 16 rows × 16 cols; `#` = foreground pixel. */
  rows: string[]
  /** State ids this shape is designed for. */
  states: string[]
  /** CSS fallback keyword for cursor. */
  fallback: string
  /** Recommended hotspot {x, y} in 32×32 space. */
  hotspot: { x: number; y: number }
}

/** Turn a rows matrix into 32×32 RGBA (2× scale), colorized. */
export function shapeToRgba(rows: string[], color: readonly [number, number, number]): Uint8Array {
  const size = 32
  const px = new Uint8Array(size * size * 4)
  for (let y = 0; y < 16; y++) {
    const row = rows[y] ?? ''
    for (let x = 0; x < 16; x++) {
      if (row[x] !== '#') continue
      // 2×2 block
      for (let dy = 0; dy < 2; dy++) {
        for (let dx = 0; dx < 2; dx++) {
          const yy = y * 2 + dy
          const xx = x * 2 + dx
          const i = (yy * size + xx) * 4
          px[i] = color[0]
          px[i + 1] = color[1]
          px[i + 2] = color[2]
          px[i + 3] = 255
        }
      }
    }
  }
  return px
}

